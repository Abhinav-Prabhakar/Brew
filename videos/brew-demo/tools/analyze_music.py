"""Read the film's music and write what the edit is cut to.

    uv run python videos/brew-demo/tools/analyze_music.py

In:  assets/music/src/champion.wav  (the track; not committed, see README)
Out: assets/music/track.wav         (the film's music: from START, 1.2x faster, ending just after the LAST hit)
     beats.js                       (window.BREW_BEATS: the eighth-note grid in film time and every drum hit on it)

The grid is fitted, not assumed: tempo and phase come from a comb search over the onset envelope (168 eighths a
minute in the track, first stomp at 4.755 s; the strong onsets sit within a few ms of it). A bar is 8 eighths; the
stomp motif hits eighths 0, 1, 2, 5, 6 of nearly every bar; the full band comes in on eighth 64.
"""

from __future__ import annotations

import json
import subprocess
import wave
from pathlib import Path

import numpy as np
from scipy import signal

HERE = Path(__file__).resolve().parents[1]
SRC = HERE / "assets" / "music" / "src" / "champion.wav"
OUT = HERE / "assets" / "music" / "track.wav"
START = 3.6  # where the film's music begins in the track (just before the first stomp)
SPEED = 1.2  # the track is played 1.2x faster (tempo only, same pitch)
LAST = 120  # the film's last hit, in eighths after the first stomp (a bar line inside the full-band section)
TAIL, FADE = 0.9, 0.8  # seconds of film after that hit, and the fade-out that ends it


def load() -> tuple[np.ndarray, int]:
    with wave.open(str(SRC)) as w:
        sr = w.getframerate()
        x = np.frombuffer(w.readframes(w.getnframes()), "<i2").reshape(-1, w.getnchannels()).mean(1) / 32768
    return x[: int(66 * sr)], sr


def onset_envelope(x: np.ndarray, sr: int, hop: int = 128, n: int = 1024) -> tuple[np.ndarray, np.ndarray]:
    f, t, z = signal.stft(x, sr, nperseg=n, noverlap=n - hop, boundary=None, padded=False)
    flux = np.maximum(0, np.diff(np.log1p(80 * np.abs(z)), axis=1)).sum(0)
    flux = np.maximum(0, flux - signal.medfilt(flux, 81))
    return t[1:], np.convolve(flux, np.hanning(7), "same")


def fit_grid(tf: np.ndarray, env: np.ndarray) -> tuple[float, float]:
    """the pulse (bpm) and the time of the first strong hit on it"""
    best = (-1.0, 0.0, 0.0)
    for bpm in np.arange(160, 180, 0.05):
        per = 60 / bpm
        for ph in np.arange(0, per, 0.004):
            idx = np.clip(np.searchsorted(tf, np.arange(ph, tf[-1], per)), 0, len(env) - 1)
            s = float(env[idx].mean())
            if s > best[0]:
                best = (s, float(bpm), float(ph))
    _, bpm, ph = best
    per = 60 / bpm
    strong = np.percentile(env, 99.5) * 0.3  # (the very first stomp is the softest of its three)
    k = 0
    while env[np.searchsorted(tf, ph + k * per - 0.03) : np.searchsorted(tf, ph + k * per + 0.03)].max(initial=0) < strong:
        k += 1
    return round(bpm, 2), ph + k * per


def main() -> None:
    x, sr = load()
    tf, env = onset_envelope(x, sr)
    bpm, t0 = fit_grid(tf, env)
    eighth = 60 / bpm
    t0 = round(t0, 3)
    norm = np.percentile(env, 99.5)
    hits = []
    for k in range(0, 2 * LAST + 1):  # every sixteenth from the first stomp to the last hit
        at = t0 + k * eighth / 2
        i0, i1 = np.searchsorted(tf, at - 0.04), np.searchsorted(tf, at + 0.04)
        v = float(np.clip(env[i0:i1].max(initial=0) / norm, 0, 1))
        if v >= 0.2:
            hits.append([k / 2, round(v, 2)])
    # film time: the track from START on, SPEED times faster
    f_eighth, f_t0 = eighth / SPEED, (t0 - START) / SPEED
    length = round(f_t0 + LAST * f_eighth + TAIL, 2)
    data = {
        "bpm": round(bpm * SPEED, 2), "eighth": round(f_eighth, 6), "t0": round(f_t0, 4), "length": length,
        "sections": {"stomps": 0, "band": 64, "end": LAST},
        "hits": hits,
    }  # fmt: skip
    (HERE / "beats.js").write_text(
        "// generated by tools/analyze_music.py: the music's eighth-note grid in film time and its drum hits ([eighth, strength])\n"
        f"window.BREW_BEATS = {json.dumps(data, separators=(',', ':'))};\n"
    )
    tmp = OUT.with_suffix(".tmp.wav")
    chain = f"atempo={SPEED},afade=t=in:st=0:d=0.12,afade=t=out:st={length - FADE}:d={FADE}"
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-ss", str(START), "-i", str(SRC), "-af", chain, "-t", str(length),
                    "-ar", "48000", str(tmp)], check=True)  # fmt: skip
    probe = subprocess.run(["ffmpeg", "-hide_banner", "-i", str(tmp), "-af", "loudnorm=print_format=summary", "-f", "null", "-"],
                           capture_output=True, text=True).stderr  # fmt: skip
    lufs = float(next(line for line in probe.splitlines() if "Input Integrated" in line).split()[2])
    gain = -14.0 - lufs
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(tmp), "-af", f"volume={gain:.2f}dB", str(OUT)], check=True)
    tmp.unlink()
    print(f"track: {bpm} eighths/min, first hit {t0} s; film: {bpm * SPEED:.1f}/min ({f_eighth * 8:.3f} s a bar), first hit {f_t0:.3f} s")
    print(f"track.wav: {length} s, {len(hits)} hits, {lufs:.1f} LUFS -> -14.0 ({gain:+.1f} dB)")


if __name__ == "__main__":
    main()
